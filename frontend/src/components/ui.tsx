/**
 * Slider with a paired numeric input. Typed values are validated against the allowed range
 * and an inline message explains what is accepted.
 */
export function RangeField({
  label,
  unit,
  value,
  min,
  max,
  step,
  onChange,
  hint,
}: {
  label: string;
  unit: string;
  value: number;
  min: number;
  max: number;
  step: number;
  onChange: (v: number) => void;
  hint?: string;
}) {
  const id = useId();
  const [text, setText] = useState(String(value));
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    setText(String(value));
    setError(null);
  }, [value]);

  const commit = (raw: string) => {
    setText(raw);
    const n = Number(raw);
    if (raw.trim() === '' || !Number.isFinite(n)) {
      setError(`Enter a number between ${min} and ${max} ${unit}.`);
    } else if (n < min || n > max) {
      setError(`${label} must be between ${min} and ${max} ${unit}.`);
    } else {
      setError(null);
      onChange(n);
    }
  };

  return (
    <div>
      <div className="mb-1 flex items-center justify-between gap-2">
        <label htmlFor={`${id}-num`} className="text-xs font-semibold text-slate-200">
          {label}
        </label>
        <div className="flex items-center gap-1">
          <input
            id={`${id}-num`}
            type="number"
            inputMode="decimal"
            min={min}
            max={max}
            step={step}
            value={text}
            onChange={(e) => commit(e.target.value)}
            onBlur={() => {
              setText(String(value));
              setError(null);
            }}
            aria-invalid={error ? true : undefined}
            aria-describedby={error ? `${id}-err` : hint ? `${id}-hint` : undefined}
            className={cx(
              'num w-16 rounded-md border bg-ink-900 px-1.5 py-1 text-right text-xs text-white',
              error ? 'border-rose-400' : 'border-line-strong',
            )}
          />
          <span className="w-6 text-xs text-slate-400">{unit}</span>
        </div>
      </div>
      <input
        type="range"
        min={min}
        max={max}
        step={step}
        value={value}
        aria-label={`${label} slider`}
        onChange={(e) => onChange(Number(e.target.value))}
        className="h-1.5 w-full cursor-pointer"
      />
      <div className="mt-1 flex justify-between text-[11px] text-slate-400">
        <span className="num">
          {min} {unit}
        </span>
        <span className="num">
          {max} {unit}
        </span>
      </div>
      {error ? (
        <p id={`${id}-err`} role="alert" className="mt-1 text-[11px] font-medium text-rose-300">
          {error}
        </p>
      ) : (
        hint && (
          <p id={`${id}-hint`} className="mt-1 text-[11px] leading-snug text-slate-400">
            {hint}
          </p>
        )
      )}
    </div>
  );
}
