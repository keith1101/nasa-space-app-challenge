export function Badge({ tone = 'slate', children, title }: { tone?: Tone; children: ReactNode; title?: string }) {
  return (
    <span
      title={title}
      className={cx(
        'inline-flex items-center gap-1 rounded-md border px-1.5 py-0.5 text-[11px] font-semibold sm:whitespace-nowrap',
        TONE_CHIP[tone],
      )}
    >
      {children}
    </span>
  );
}

export type DataKind = 'observed' | 'derived' | 'estimated' | 'simulated';

const KIND_META: Record<DataKind, { label: string; tone: Tone; dashed: boolean; hint: string }> = {
  observed: {
    label: 'Observed',
    tone: 'emerald',
    dashed: false,
    hint: 'Measured by satellites and distributed by NASA FIRMS.',
  },
  derived: {
    label: 'Derived',
    tone: 'cyan',
    dashed: false,
    hint: 'Computed by this project from observed detections using a deterministic algorithm.',
  },
  estimated: {
    label: 'Estimated',
    tone: 'amber',
    dashed: true,
    hint: 'Extrapolated from a limited observation window. Not a full observation.',
  },
  simulated: {
    label: 'Simulated reference',
    tone: 'amber',
    dashed: true,
    hint: 'Generated by a parametric climatological model. These values are not NASA observations.',
  },
};

/** Every chart declares whether its data is observed, derived, estimated or simulated. */
export function DataKindTag({ kind, detail }: { kind: DataKind; detail?: string }) {
  const meta = KIND_META[kind];
  return (
    <span
      title={meta.hint}
      className={cx(
        'inline-flex items-center gap-1 whitespace-nowrap rounded-md border px-1.5 py-0.5 text-[11px] font-semibold',
        TONE_CHIP[meta.tone],
        meta.dashed && 'border-dashed',
      )}
    >
      {meta.label}
      {detail ? <span className="font-normal opacity-80">· {detail}</span> : null}
    </span>
  );
}

