export function Notice({
  tone,
  title,
  children,
}: {
  tone: 'info' | 'warning' | 'error' | 'success';
  title?: string;
  children: ReactNode;
}) {
  const styles = {
    info: { box: 'border-sky-400/30 bg-sky-400/5', icon: 'text-sky-300', Icon: Info },
    warning: { box: 'border-amber-400/40 bg-amber-400/5', icon: 'text-amber-300', Icon: AlertTriangle },
    error: { box: 'border-rose-400/40 bg-rose-400/5', icon: 'text-rose-300', Icon: AlertTriangle },
    success: { box: 'border-emerald-400/30 bg-emerald-400/5', icon: 'text-emerald-300', Icon: CheckCircle2 },
  }[tone];
  return (
    <div
      role={tone === 'error' ? 'alert' : 'status'}
      className={cx('flex gap-2.5 rounded-lg border px-3 py-2.5 text-xs leading-relaxed text-slate-300', styles.box)}
    >
      <styles.Icon className={cx('mt-0.5 h-4 w-4 shrink-0', styles.icon)} aria-hidden="true" />
      <div>
        {title && <div className="mb-0.5 font-semibold text-white">{title}</div>}
        {children}
      </div>
    </div>
  );
}

