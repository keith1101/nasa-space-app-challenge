import { useEffect, useId, useState, type ReactNode } from 'react';
import { AlertTriangle, CheckCircle2, Info, Loader2, type LucideIcon } from 'lucide-react';

export type Tone = 'cyan' | 'blue' | 'amber' | 'rose' | 'emerald' | 'slate';

const TONE_TEXT: Record<Tone, string> = {
  cyan: 'text-cyan-300',
  blue: 'text-sky-300',
  amber: 'text-amber-300',
  rose: 'text-rose-300',
  emerald: 'text-emerald-300',
  slate: 'text-slate-300',
};

const TONE_CHIP: Record<Tone, string> = {
  cyan: 'border-cyan-400/30 bg-cyan-400/10 text-cyan-200',
  blue: 'border-sky-400/30 bg-sky-400/10 text-sky-200',
  amber: 'border-amber-400/35 bg-amber-400/10 text-amber-200',
  rose: 'border-rose-400/35 bg-rose-400/10 text-rose-200',
  emerald: 'border-emerald-400/30 bg-emerald-400/10 text-emerald-200',
  slate: 'border-line-strong bg-ink-700/70 text-slate-300',
};

export function cx(...parts: Array<string | false | null | undefined>): string {
  return parts.filter(Boolean).join(' ');
}

export function Card({
  children,
  className,
  as: Tag = 'section',
  ...rest
}: {
  children: ReactNode;
  className?: string;
  as?: 'section' | 'div' | 'article' | 'aside';
  'aria-labelledby'?: string;
  'aria-label'?: string;
}) {
  return (
    <Tag className={cx('rounded-xl border border-line bg-ink-800/80 shadow-panel', className)} {...rest}>
      {children}
    </Tag>
  );
}

