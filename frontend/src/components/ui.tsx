export function Segmented<T extends string>({
  label,
  value,
  options,
  onChange,
  className,
}: {
  label: string;
  value: T;
  options: ReadonlyArray<{ value: T; label: string }>;
  onChange: (v: T) => void;
  className?: string;
}) {
  return (
    <div
      role="group"
      aria-label={label}
      className={cx('inline-flex w-full rounded-lg border border-line bg-ink-900/70 p-0.5', className)}
    >
      {options.map((o) => {
        const active = o.value === value;
        return (
          <button
            key={o.value}
            type="button"
            aria-pressed={active}
            onClick={() => onChange(o.value)}
            className={cx(
              'flex-1 rounded-md px-2.5 py-1.5 text-xs font-semibold transition-colors',
              active ? 'bg-ink-500 text-white shadow-sm' : 'text-slate-400 hover:bg-ink-700/70 hover:text-slate-100',
            )}
          >
            {o.label}
          </button>
        );
      })}
    </div>
  );
}

